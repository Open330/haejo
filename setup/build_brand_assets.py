"""Generate the Haejo (해줘) brand system: mark, Latin and Hangul wordmarks, lockups,
app icon (.icns), favicon, menu-bar templates, working animation, banner and social card.

The SVGs are written from the constants below, so the vector source and the raster icon
cannot drift apart. Rasterizing uses AppKit's own SVG renderer (through a small Swift
program) and iconutil; nothing is downloaded. Brand rules: docs/haejo-branding.md.

    python3 setup/build_brand_assets.py               # write SVGs + .icns
    python3 setup/build_brand_assets.py --check       # tracked SVGs are current (no rendering)
    python3 setup/build_brand_assets.py --preview-dir DIR   # also write a review sheet
"""
import argparse
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# macOS icon grid: 1024 canvas, 824 body inset 100, continuous-corner radius.
CANVAS, BODY, INSET, RADIUS = 1024, 824, 100, 185.4

ROOT = Path(__file__).resolve().parent.parent
OUT = "docs/assets/brand/haejo/"
GENERATED = "Generated by setup/build_brand_assets.py. Edit the script, not this file."

# Palette carried over from Tacto: ink structure, ivory ground, one sunrise accent.
INK, IVORY, SUN, SUN_TEXT, MOSS = "#1b211c", "#f6f4ed", "#fa6b3b", "#c4532c", "#5f6b58"
CAP = 'fill="none" stroke-linecap="round" stroke-linejoin="round"'
FLAT = 'fill="none" stroke-linecap="butt" stroke-linejoin="miter"'
FONT = "-apple-system,'Apple SD Gothic Neo','Helvetica Neue',Arial,sans-serif"

# ---------------------------------------------------------------- the mark
# ㅎ, the first letter of 해줘, on a 32-unit grid.
#   sun (dot)     = the ask, and 해 (the sun). It rises from behind the bar in motion.
#   bar           = the blank you fill in: "Ask Haejo to ____". Also the Flow it records.
#   ring          = the result, checked and closed.
# Proportion rules
#   * The bar is about 1.55x the ring's width, as in a well-drawn Hangul ㅎ, so the
#     mark fills the square sideways instead of stacking into a narrow column.
#   * The sun should look the same size as the ring's counter. A filled disc looks
#     larger than an equal hole, so it is drawn at 0.72x the counter (optical correction).
#   * The j of the wordmark uses the same round sun, so mark and word share one dot.
OPTICAL = {
    #          stroke  counter  gap(sun-bar)  gap(bar-ring)  bar width  sun scale
    "regular": (4.0, 9.4, 1.5, 1.7, 27.0, 0.72),
    "small": (4.6, 8.4, 1.4, 1.6, 27.4, 0.80),
}
BAR_CAP = "butt"


class Geo:
    def __init__(self, optical="regular"):
        self.w, c, g1, g2, bw, ds = OPTICAL[optical]
        ro = c / 2 + self.w
        self.ro, self.rr = ro, ro - self.w / 2          # ring outer / path radius
        self.dr = c / 2 * ds                            # sun radius
        height = 2 * self.dr + g1 + self.w + g2 + 2 * ro
        top = (32 - height) / 2
        self.dot_cy = top + self.dr
        self.bar_y = top + 2 * self.dr + g1 + self.w / 2
        self.cy = self.bar_y + self.w / 2 + g2 + ro
        self.bottom = self.cy + ro
        self.rise = 2 * self.dr + g1                    # distance the sun travels in the animation
        self.x0, self.x1 = 16 - bw / 2, 16 + bw / 2
        self.center = (16, 16)


def r2(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def sun_el(optical="regular", fill=SUN, inner=""):
    g = Geo(optical)
    if inner:
        return f'<circle cx="16" cy="{r2(g.dot_cy)}" r="{r2(g.dr)}" fill="{fill}">{inner}</circle>'
    return f'<circle cx="16" cy="{r2(g.dot_cy)}" r="{r2(g.dr)}" fill="{fill}"/>'


def bar_path(optical="regular"):
    g = Geo(optical)
    return f"M{r2(g.x0)} {r2(g.bar_y)}H{r2(g.x1)}"


def mark(ink=INK, sun=SUN, optical="regular", indent="  ", ring_fill="none"):
    g = Geo(optical)
    return (f'{indent}{sun_el(optical, sun)}\n'
            f'{indent}<path d="{bar_path(optical)}" fill="none" stroke="{ink}" stroke-width="{g.w}" stroke-linecap="{BAR_CAP}"/>\n'
            f'{indent}<circle cx="16" cy="{r2(g.cy)}" r="{r2(g.rr)}" fill="{ring_fill}" stroke="{ink}" stroke-width="{g.w}"/>')


MARK_CENTER = Geo().center

# ------------------------------------------------------------- wordmarks
# "haejo": a geometric grotesk drawn for the brand. x-height 16 on baseline 29,
# stroke 4.0 (25% of x-height), flat terminals, optically kerned spacing. Bowls are true
# circles like the mark's ring; the coral tittle on the j is the only accent.
LW, LXH, LBASE, LASC = 4.0, 16, 29, 8
KERN = {"ha": 2.0, "ae": 1.9, "ej": 1.5, "jo": 2.1}   # optical spacing, not one fixed gap


def _latin_geometry():
    import math
    R = LXH / 2; r = R - LW / 2; cy = LBASE - R; top = LBASE - LXH
    x, d = 0.0, []
    s0 = x + LW / 2                                                    # h
    d.append(f"M{r2(s0)} {LASC}V{LBASE}M{r2(s0)} {r2(cy)}A{r2(r)} {r2(r)} 0 0 1 {r2(s0 + 2 * r)} {r2(cy)}V{LBASE}")
    x += 2 * R + KERN["ha"]
    cx = x + R                                                         # a
    d.append(f"M{r2(cx + r)} {r2(cy)}A{r2(r)} {r2(r)} 0 1 0 {r2(cx - r)} {r2(cy)}A{r2(r)} {r2(r)} 0 1 0 {r2(cx + r)} {r2(cy)}"
             f"M{r2(cx + r)} {r2(top)}V{LBASE}")
    x += 2 * R + KERN["ae"]
    cx = x + R; a = math.radians(40)                                   # e
    d.append(f"M{r2(cx - r)} {r2(cy)}H{r2(cx + r)}A{r2(r)} {r2(r)} 0 1 0 {r2(cx + r * math.cos(a))} {r2(cy + r * math.sin(a))}")
    x += 2 * R + KERN["ej"]
    jx, hk = x + LW / 2, 3.6                                           # j
    d.append(f"M{r2(jx)} {r2(top)}V{LBASE + 1}A{hk} {hk} 0 0 1 {r2(jx - hk)} {LBASE + 1 + hk}")
    x += LW + KERN["jo"]
    cx = x + R                                                         # o
    d.append(f"M{r2(cx + r)} {r2(cy)}A{r2(r)} {r2(r)} 0 1 0 {r2(cx - r)} {r2(cy)}A{r2(r)} {r2(r)} 0 1 0 {r2(cx + r)} {r2(cy)}")
    x += 2 * R
    return " ".join(d), (jx, top - 4.7, LW * 0.68), x


LATIN, LATIN_DOT, LATIN_W = _latin_geometry()
LATIN_H = 36                      # descender reaches ~35.7

# "해줘": same weight and flat terminals as the Latin; the ㅎ of 해 is the mark in
# miniature with the same rules.
HW = 4.0
HANGUL = ('<path d="M0.5 8.6H15.5"/><circle cx="8" cy="19.6" r="5.2"/>'      # ㅎ bar + ring
          '<path d="M21 3V31M21 16.5H28M29.5 1.5V31.5"/>'                     # ㅐ
          '<path d="M34 4.5H48M41 4.5L34.5 13.5M41 8.5L48 13.5"/>'           # ㅈ
          '<path d="M32.5 19H49.5M41 19V29.5"/>'                              # ㅜ
          '<path d="M58 1.5V31.5M51.5 15H58"/>')                              # ㅓ
HANGUL_SUN, HANGUL_W = (8, 3.2, 2.3), 60          # cx, cy, r: ㅎ dot at 0.72x its counter

LOCK_X, LOCK_Y = 37, 2.4          # word offset in the horizontal lockup (baseline meets the ring's bottom)


def latin(ink=INK, sun=SUN, x=0, y=0, indent="  "):
    jx, jy, jr = LATIN_DOT
    return (f'{indent}<g transform="translate({r2(x)} {r2(y)})">'
            f'<path d="{LATIN}" stroke="{ink}" stroke-width="{LW}" {FLAT}/>'
            f'<circle cx="{r2(jx)}" cy="{r2(jy)}" r="{r2(jr)}" fill="{sun}"/></g>')


def hangul(ink=INK, sun=SUN, x=0, y=0, indent="  "):
    return (f'{indent}<g transform="translate({r2(x)} {r2(y)})">'
            f'<circle cx="{HANGUL_SUN[0]}" cy="{HANGUL_SUN[1]}" r="{HANGUL_SUN[2]}" fill="{sun}"/>'
            f'<g stroke="{ink}" stroke-width="{HW}" {FLAT}>{HANGUL}</g></g>')


def svg(name, w, h, vb, title, body, note=""):
    note = f"\n       {note}" if note else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{float(w):g}" height="{float(h):g}" viewBox="{vb}" '
            f'role="img" aria-labelledby="{name}-title">\n  <title id="{name}-title">{title}</title>\n'
            f'  <!-- {GENERATED}{note} -->\n{body}\n</svg>\n')


def mark_svg(ink=INK, name="haejo-mark"):
    return svg(name, 32, 32, "0 0 32 32", "Haejo", mark(ink),
               "해돋이 ㅎ: sun (the ask), horizon bar (the Flow), ring (the verified result). Sun diameter = ring counter.")


def lockup_svg(ink=INK, name="haejo-lockup"):
    w, h = LOCK_X + LATIN_W, LOCK_Y + LATIN_H
    return svg(name, r2(w * 2), r2(h * 2), f"0 0 {r2(w)} {r2(h)}", "Haejo",
               mark(ink) + "\n" + latin(ink, x=LOCK_X, y=LOCK_Y),
               "Horizontal lockup. Word baseline meets the bottom of the ring.")


def lockup_ko_svg(ink=INK, name="haejo-lockup-ko"):
    w = LOCK_X + HANGUL_W
    return svg(name, w * 2, 66, f"0 0 {w} 33", "해줘", mark(ink) + "\n" + hangul(ink, x=LOCK_X, y=0),
               "Hangul lockup for Korean-first surfaces.")


def lockup_stacked_svg(ink=INK, name="haejo-lockup-stacked"):
    w, s = LATIN_W, 1.6
    body = (f'  <g transform="translate({r2((w - 32 * s) / 2)} 0) scale({s})">\n{mark(ink, indent="    ")}\n  </g>\n'
            + latin(ink, x=0, y=50))
    return svg(name, r2(w * 2), 172, f"0 0 {r2(w)} 86", "Haejo", body, "Stacked lockup for square placements.")


def word_svg(ink=INK, name="haejo-word"):
    return svg(name, r2(LATIN_W * 2), LATIN_H * 2, f"0 0 {r2(LATIN_W)} {LATIN_H}", "Haejo", latin(ink))


def hangul_svg(ink=INK, name="haejo-hangul"):
    return svg(name, HANGUL_W * 4, 136, f"0 -1 {HANGUL_W} 34", "해줘", hangul(ink))


# ----------------------------------------------------------- icons
def icon_svg(optical="regular", tile=INK, ink=IVORY, sun=SUN, name="haejo-app-icon"):
    scale = 17.0 if optical == "regular" else 18.5
    c = Geo(optical).center
    tx, ty = CANVAS / 2 - c[0] * scale, CANVAS / 2 - c[1] * scale
    body = (f'  <rect x="{INSET}" y="{INSET}" width="{BODY}" height="{BODY}" rx="{RADIUS}" fill="{tile}"/>\n'
            f'  <rect x="{INSET + 1}" y="{INSET + 1}" width="{BODY - 2}" height="{BODY - 2}" rx="{RADIUS - 1}" '
            f'fill="none" stroke="{ink}" stroke-opacity="0.2" stroke-width="3"/>\n'
            f'  <g transform="translate({tx:.2f} {ty:.2f}) scale({scale})">\n{mark(ink, sun, optical, "    ")}\n  </g>')
    return svg(name, CANVAS, CANVAS, f"0 0 {CANVAS} {CANVAS}", "Haejo", body,
               f"macOS grid: {BODY} px body inset {INSET} px; {optical} optical size.")


def favicon_svg():
    body = (f'  <rect width="32" height="32" rx="8" fill="{INK}"/>\n'
            f'  <g transform="translate(2.4 2.4) scale(0.85)">\n{mark(IVORY, SUN, "small", "    ")}\n  </g>')
    return svg("haejo-favicon", 32, 32, "0 0 32 32", "Haejo", body)


