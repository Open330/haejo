def build_icns(renderer, out):
    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / "Haejo.iconset"
        iconset.mkdir()
        for name, pixels, optical in ICONSET:
            renderer.render(icon_svg(optical), iconset / name, pixels)
        subprocess.run(["iconutil", "-c", "icns", "-o", str(out), str(iconset)], check=True)


def preview(renderer, out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    renderer.render(icon_svg("regular"), out / "icon-512.png", 512)
    renderer.render(icon_svg("regular", IVORY, INK), out / "icon-ivory-512.png", 512)
    for px in (16, 32, 64):
        renderer.render(icon_svg("small" if px <= 32 else "regular"), out / f"icon-{px}.png", px)
    places = [(out / "icon-512.png", 20, 20, 512, False), (out / "icon-ivory-512.png", 560, 20, 512, False),
              (out / "icon-16.png", 1100, 40, 16, True), (out / "icon-32.png", 1100, 80, 32, True),
              (out / "icon-64.png", 1100, 140, 64, True)]
    for i, s in enumerate(STATES):
        renderer.render(state_svg(s), out / f"state-{s}.png", 36)
        places.append((out / f"state-{s}.png", 1100, 240 + i * 50, 36, False))
    renderer.sheet(out / "sheet.png", 1200, 560, "#ffffff", places)
    print(f"preview: {out / 'sheet.png'}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a tracked SVG is out of date")
    parser.add_argument("--preview-dir", help="also write a review sheet here")
    args = parser.parse_args()
    if args.check:
        stale = [n for n, make in TRACKED.items()
                 if not (ROOT / n).exists() or (ROOT / n).read_text() != make()]
        if stale:
            print("stale:", *stale, sep="\n  ")
            return 1
        print("haejo brand assets are current")
        return 0
    for name, make in TRACKED.items():
        (ROOT / name).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / name).write_text(make())
    if not shutil.which("swiftc") or not shutil.which("iconutil"):
        print("swiftc/iconutil missing: SVGs written, .icns skipped")
        return 0
    with tempfile.TemporaryDirectory() as work:
        renderer = Renderer(work)
        build_icns(renderer, ROOT / ICNS)
        if args.preview_dir:
            preview(renderer, args.preview_dir)
    print(f"wrote {len(TRACKED)} SVGs and {ICNS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
